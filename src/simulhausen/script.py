"""Script steps: ``user()``, ``agent()``, ``judge()``, ``message()``, ``proceed()``,
``succeed()``, ``fail()``, plus plain callables used as assertions.

A callable step receives the :class:`~simulhausen.types.ScenarioState` and may
be sync or async. Raising ``AssertionError`` in it fails the scenario; the
runner records the failure and re-raises so pytest shows it as usual. A
callable that returns ``succeed(...)`` or ``fail(...)`` ends the scenario the
same way those steps do; one that returns ``judge(...)`` ends the dialogue
there and lets that verdict decide.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from simulhausen.types import Role, ScenarioState

__all__ = [
    "AgentStep",
    "FailStep",
    "JudgeStep",
    "MessageStep",
    "ProceedStep",
    "ScriptStep",
    "StateCallback",
    "SucceedStep",
    "UserStep",
    "agent",
    "fail",
    "judge",
    "message",
    "proceed",
    "succeed",
    "user",
]

# Callback that sees the state after a turn or step; may be sync or async.
type StateCallback = Callable[[ScenarioState], Any | Awaitable[Any]]


@dataclass(frozen=True)
class UserStep:
    """A user message: fixed text, or ``None`` to let the user simulator write it."""

    content: str | None = None


@dataclass(frozen=True)
class AgentStep:
    """An agent turn: call the adapter, or inject ``content`` without calling it."""

    content: str | None = None


@dataclass(frozen=True)
class MessageStep:
    """Append a message verbatim, without calling any agent."""

    role: Role
    content: str


@dataclass(frozen=True)
class JudgeStep:
    """Ask the judge for a verdict.

    Without ``criteria`` the judge grades the criteria it was built with. That
    is the final verdict (a later one replaces it), and the steps after it
    still run, which suits deterministic assertions. With ``criteria`` it is a
    checkpoint: the scenario fails right there if any of them fails and goes
    on otherwise.
    """

    criteria: tuple[str, ...] | None = None
    additional_context: str | None = None


@dataclass(frozen=True)
class ProceedStep:
    """Let the user simulator and the agent talk on their own for a while."""

    turns: int | None = None
    on_turn: StateCallback | None = None
    on_step: StateCallback | None = None


@dataclass(frozen=True)
class SucceedStep:
    """End the scenario as passed, skipping the remaining steps and the judge."""

    reasoning: str | None = None


@dataclass(frozen=True)
class FailStep:
    """End the scenario as failed, skipping the remaining steps and the judge."""

    reasoning: str | None = None


type ScriptStep = (
    UserStep
    | AgentStep
    | MessageStep
    | JudgeStep
    | ProceedStep
    | SucceedStep
    | FailStep
    | Callable[[ScenarioState], Any | Awaitable[Any]]
)


def user(content: str | None = None) -> UserStep:
    """User turn: the given text, or a message generated by the user simulator."""
    return UserStep(content=content)


def agent(content: str | None = None) -> AgentStep:
    """Agent turn: call the agent under test, or inject a fixed reply when ``content`` is given."""
    return AgentStep(content=content)


def message(role: Role, content: str) -> MessageStep:
    """Append a message to the transcript as is (useful to seed prior context)."""
    return MessageStep(role=role, content=content)


def judge(criteria: list[str] | None = None, *, additional_context: str | None = None) -> JudgeStep:
    """Judge verdict: the judge's own criteria (final), or inline ``criteria`` (checkpoint).

    ``additional_context`` goes to the judge as extra evidence the dialogue does
    not show, such as database or file state after the agent acted.
    """
    if criteria is not None and not criteria:
        raise ValueError("judge(criteria=[]) has nothing to check; pass None to use the judge's own criteria")
    return JudgeStep(criteria=tuple(criteria) if criteria is not None else None, additional_context=additional_context)


def proceed(
    turns: int | None = None,
    *,
    on_turn: StateCallback | None = None,
    on_step: StateCallback | None = None,
) -> ProceedStep:
    """Let the simulation run unscripted.

    Each turn is a simulated user message followed by an agent reply. It stops
    after ``turns`` turns (``None``: until ``max_turns`` is reached), when the
    user simulator reports the goal as achieved, or when the judge concludes,
    in which case the judge's verdict ends the scenario. ``on_turn`` runs after
    every full turn, ``on_step`` after every single message.
    """
    if turns is not None and turns < 1:
        raise ValueError("proceed(turns=...) must be at least 1")
    return ProceedStep(turns=turns, on_turn=on_turn, on_step=on_step)


def succeed(reasoning: str | None = None) -> SucceedStep:
    """End the scenario as passed right here."""
    return SucceedStep(reasoning=reasoning)


def fail(reasoning: str | None = None) -> FailStep:
    """End the scenario as failed right here."""
    return FailStep(reasoning=reasoning)
